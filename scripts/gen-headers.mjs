// Builds the Content-Security-Policy (with the hash of the inline import map) for both targets:
// server/csp.js (Node) and web/_headers (Cloudflare static assets). Run after editing web/index.html.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
const html = readFileSync(new URL("../web/index.html", import.meta.url), "utf8");
const im = html.match(/<script type="importmap">([\s\S]*?)<\/script>/)[1];
const hash = createHash("sha256").update(im).digest("base64");
const csp = [
  "default-src 'self'",
  `script-src 'self' 'sha256-${hash}'`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https://tile.openstreetmap.org https://server.arcgisonline.com",
  "connect-src 'self' data: blob: https://nominatim.openstreetmap.org https://openrouter.ai https://api.open-meteo.com",
  "worker-src 'self' blob:",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join("; ");
writeFileSync(new URL("../server/csp.js", import.meta.url), `// Generated by scripts/gen-headers.mjs\nexport const CSP = ${JSON.stringify(csp)};\n`);
writeFileSync(new URL("../web/_headers", import.meta.url), `/*\n  Content-Security-Policy: ${csp}\n  X-Content-Type-Options: nosniff\n  Referrer-Policy: no-referrer\n  X-Frame-Options: DENY\n  Permissions-Policy: geolocation=(), camera=(), microphone=()\n`);
console.log("csp ok");
